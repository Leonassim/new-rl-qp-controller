#!/usr/bin/env bash
# mc_mujoco_stairs.sh [h] [tread] [-- mc_mujoco args]: mc_mujoco with the stairs policy's training terrain.
#
#   h       riser height in m (default 0.04). Training covers 0.005-0.18; slot 22 holds ~0.02-0.05.
#   tread   0.27 or 0.30 (default 0.27), the two training treads.
#
# mjlab's StepPyramidCfg: 3 nested boxes, 1.6 m platform, first riser 0.30 m ahead of the pelvis (training
# spawns at 0.15-0.35). Climb, stop on the platform, then forward again goes down the far side: no turn needed.
# The policy only saw forward or stop on stairs.
#
# Writes the scene object into mc_mujoco's user folder for this run and removes it on exit, exports
# RLQP_STAIRS (same geometry) for obs_format 11's analytic height scan, preselects slot 22. Arm from the GUI.
# RLQP_VISION=1: slot 23 (obs_format 12) and scripts/vision/rhps1_vision.py --source sim beside mc_mujoco, the
# onboard height map through shared memory (log: $RLQP_VISION_LOG, default /tmp/rhps1_vision.log; extra options in
# $RLQP_VISION_ARGS).
set -eu
H=${1:-0.04}
T=${2:-0.27}
[ $# -ge 2 ] && shift 2 || shift $#
[ "${1:-}" = "--" ] && shift
N=3
P=1.6
GAP=0.30
U="$HOME/.config/mc_rtc/mc_mujoco"
MARK="# Generated by mc_mujoco_stairs.sh"

mkdir -p "$U"
if [ -f "$U/mc_mujoco.yaml" ] && ! grep -q "^$MARK" "$U/mc_mujoco.yaml"; then
  echo "mc_mujoco_stairs: $U/mc_mujoco.yaml exists and is not ours, refusing to overwrite it" >&2
  exit 1
fi

CX=$(python3 -c "print(round($GAP + $P / 2 + ($N - 1) * $T, 4))")
python3 - "$U/rhps1_stairs.xml" "$H" "$T" "$N" "$P" <<'EOF'
import sys
out, h, t, n, p = sys.argv[1], float(sys.argv[2]), float(sys.argv[3]), int(sys.argv[4]), float(sys.argv[5])
g = []
for k in range(1, n + 1):
  half = p / 2 + (n - k) * t
  zt = k * h
  s = 0.6 + 0.4 * k / n  # orange, lighter going up: mc_mujoco's floor is a blue checker
  g.append(f'      <geom name="step{k}" type="box" size="{half:.4f} {half:.4f} {zt / 2:.4f}" pos="0 0 {zt / 2:.4f}" '
           f'condim="3" group="1" rgba="{s:.3f} {0.6 * s:.3f} {0.25 * s:.3f} 1"/>')  # mc_mujoco hides group 0
open(out, "w").write('<mujoco model="rhps1_stairs">\n  <worldbody>\n    <body name="base" pos="0 0 0">\n'
                     + "\n".join(g) + "\n    </body>\n  </worldbody>\n</mujoco>\n")
EOF
cat > "$U/rhps1_stairs.yaml" <<EOF
$MARK, removed on exit.
xmlModelPath: "$U/rhps1_stairs.xml"
EOF
cat > "$U/mc_mujoco.yaml" <<EOF
$MARK, removed on exit.
objects:
  stairs:
    module: rhps1_stairs
    init_pos:
      translation: [$CX, 0.0, 0.0]
      rotation: [0.0, 0.0, 0.0]
EOF
VIS=""
cleanup() {
  rm -f "$U/mc_mujoco.yaml" "$U/rhps1_stairs.yaml" "$U/rhps1_stairs.xml"
  [ -n "$VIS" ] && kill -TERM "$VIS" 2>/dev/null || true
}
CHILD=""
trap cleanup EXIT
# The child runs in the background (a foreground one defers the trap until it exits) and so ignores SIGINT:
# the trap forwards Ctrl-C and TERM to it.
trap 'cleanup; [ -n "$CHILD" ] && kill -TERM "$CHILD" 2>/dev/null && wait "$CHILD"; exit 130' INT TERM

export RLQP_STAIRS="$CX 0 0 $H $T $N $P"
if [ "${RLQP_VISION:-0}" = 1 ]; then
  export RLQP_BENCH_POLICY_INDEX=${RLQP_BENCH_POLICY_INDEX:-23}
  rm -f /dev/shm/rhps1_vision_pose /dev/shm/rhps1_vision_map  # a previous run's map carries its own clock
  # shellcheck disable=SC2086  # RLQP_VISION_ARGS: extra options, e.g. --align
  python3 "$(dirname "$(readlink -f "$0")")/vision/rhps1_vision.py" --source sim ${RLQP_VISION_ARGS:-} \
    > "${RLQP_VISION_LOG:-/tmp/rhps1_vision.log}" 2>&1 &
  VIS=$!
fi
export RLQP_BENCH_POLICY_INDEX=${RLQP_BENCH_POLICY_INDEX:-22}
# Slot 22 trained on the drive plant: drive model and the robot's ~30 ms post-QP latency, as the gates run it.
export MC_MUJOCO_RHPS1_DRIVE=${MC_MUJOCO_RHPS1_DRIVE:-1} MC_MUJOCO_RHPS1_DRIVE_ROT=${MC_MUJOCO_RHPS1_DRIVE_ROT:-KNEE} \
  RLQP_BENCH_DELAY_MS=${RLQP_BENCH_DELAY_MS:-30}
echo "mc_mujoco_stairs: $N marches de $H m, giron $T m, palier $P m, centre x=$CX ; slot $RLQP_BENCH_POLICY_INDEX," \
  "drive $MC_MUJOCO_RHPS1_DRIVE ($MC_MUJOCO_RHPS1_DRIVE_ROT), retard ${RLQP_BENCH_DELAY_MS} ms" >&2
mc_mujoco "$@" &
CHILD=$!
wait "$CHILD"
